import test from 'node:test';
import assert from 'node:assert/strict';
import * as M from '../model.js';
import * as R from '../engine.js';
import { demo } from './fixture.mjs';

const cmd = (m, question, value, target = 'system', note = 'Reviewer context', evidence = '') => M.validate(R.command(m, { type: 'answer', target, question, value, note, evidence }));

test('branched review, unknowns, prerequisites, v1 migration, persistence, evidence, invalidation, N/A propagation, scope/revision conflicts and proposal-only authority', async () => {
  let model = demo();
  assert.equal(model.version, 2);
  assert.equal(R.questions(model)[0].id, 'purpose');
  const original = JSON.stringify(model);
  assert.throws(() => cmd(model, 'actors', 'public'), /first/);
  assert.equal(JSON.stringify(model), original, 'Failed commands cannot mutate');
  assert.throws(() => cmd(model, 'purpose', 'verified'), /Invalid answer/);
  assert.throws(() => R.command(model, { type: 'close-finding' }), /Unsupported/);
  assert.throws(() => R.command(model, { type: 'answer', target: 'system', question: 'purpose', value: 'documented', note: 'x', evidence: '', verified: true }), /field/);
  model = cmd(model, 'purpose', 'unknown', 'system', '');
  assert(R.pending(model).some(q => q.id === 'purpose'));
  assert.throws(() => cmd(model, 'actors', 'public'), /first/);
  model = cmd(model, 'purpose', 'documented');
  model = cmd(model, 'actors', 'third-parties');
  model = cmd(model, 'data', 'sensitive');
  model = cmd(model, 'tenants', 'multiple');
  assert(R.questions(model).some(q => q.id === 'isolation'));
  model = cmd(model, 'isolation', 'unknown', 'system', '');
  model = cmd(model, 'access', 'service-only', 'n:worker');
  assert(R.questions(model, 'n:worker').some(q => q.id === 'retries' && !q.blocked));
  assert(!R.questions(model, 'n:table').some(q => q.id === 'retries'));
  for (const type of ['AWS::SQS::QueuePolicy', 'AWS::Lambda::Version', 'AWS::IAM::Role', 'AWS::Logs::LogGroup', 'AWS::CloudWatch::Alarm', 'AWS::ApiGateway::Method', 'AWS::Lambda::Permission']) {
    const auxiliary = structuredClone(model); auxiliary.nodes[0].type = type;
    assert.deepEqual(R.questions(auxiliary, 'n:client'), [], type);
  }
  const conditional = M.validate({ version: 1, documentType: 'snapshot', source: 'snapshot', id: 'conditional', scope: {}, zones: [], edges: [],
    nodes: [{ id: 'Queue', name: 'Queue', type: 'AWS::SQS::Queue', status: 'CONDITIONAL_NOT_RECORDED', zone: '' }] });
  assert.equal(conditional.nodes[0].status, 'CONDITIONAL_NOT_RECORDED');
  assert.deepEqual(R.questions(conditional, 'n:Queue'), []);
  assert(!R.pending(conditional).some(q => q.target === 'n:Queue'));
  assert.throws(() => cmd(model, 'identity', 'documented', 'e:demo-0'), /not applicable/);
  model = cmd(model, 'boundary', 'crossing', 'e:demo-0');
  assert(R.questions(model, 'e:demo-0').some(q => q.id === 'identity'));
  model = cmd(model, 'identity', 'documented', 'e:demo-0', 'SigV4 validation expected', 'test-plan.md#identity');
  const restored = M.importModel(M.parse(JSON.stringify({ ...model, documentType: 'review' })));
  assert.deepEqual(restored.review, model.review);
  const input = { type: 'answer', target: 'system', question: 'audit', value: 'documented', note: 'Test references', evidence: 'validation.md' };
  const p = await R.proposal(model, input);
  assert.equal(JSON.stringify(model.review), JSON.stringify(restored.review), 'Proposal creation cannot commit');
  const moved = structuredClone(model); moved.nodes[0].x += 20;
  assert.equal(await R.digest(moved), await R.digest(model));
  const accepted = await R.checkProposal(moved, p);
  assert.equal(R.answer(accepted, 'system', 'audit').origin, 'agent-reviewed');
  await assert.rejects(R.checkProposal(cmd(model, 'tenants', 'single'), p), /Stale/);
  const crossScope = structuredClone(model); crossScope.scope.region = 'us-east-2';
  await assert.rejects(R.checkProposal(crossScope, p), /Stale/);
  await assert.rejects(R.checkProposal(model, { ...p, command: { type: 'delete-stack' } }), /Unsupported/);
  assert.throws(() => cmd(model, 'access', 'not-applicable', 'n:worker', ''), /rationale/);
  const queueNA = cmd(model, 'access', 'not-applicable', 'n:queue', 'This component is outside the review scope');
  const queueQuestions = R.questions(queueNA, 'n:queue');
  assert.deepEqual(queueQuestions.filter(q => q.notApplicable).map(q => q.id), ['privilege', 'retries']);
  assert(queueQuestions.filter(q => q.notApplicable).every(q => q.blocked && q.blockedReason.includes('n:queue|access')));
  assert(!R.pending(queueNA).some(q => q.target === 'n:queue'));
  assert.equal(queueNA.review.answers.filter(a => a.target === 'n:queue').length, 1, 'Inherited N/A must not fabricate stored answers');
  assert.throws(() => cmd(queueNA, 'privilege', 'declared', 'n:queue'), /Not applicable/);
  await assert.rejects(R.proposal(queueNA, { type: 'answer', target: 'n:queue', question: 'retries', value: 'documented', note: 'Attempt to bypass N/A', evidence: '' }), /Not applicable/);
  const reopened = cmd(queueNA, 'access', 'service-only', 'n:queue');
  assert(R.questions(reopened, 'n:queue').every(q => !q.notApplicable));
  assert.deepEqual(R.pending(reopened).filter(q => q.target === 'n:queue').map(q => q.id), ['privilege', 'retries']);
  const staleNA = R.invalidate(queueNA);
  assert(R.questions(staleNA, 'n:queue').every(q => !q.notApplicable));
  assert.equal(R.pending(staleNA).filter(q => q.target === 'n:queue').length, 3);
  const unknownAccess = cmd(model, 'access', 'unknown', 'n:queue', '');
  assert.equal(R.pending(unknownAccess).filter(q => q.target === 'n:queue').length, 3);
  assert(R.questions(unknownAccess, 'n:queue').filter(q => q.id !== 'access').every(q => q.blocked && !q.notApplicable));
  const systemNA = cmd(demo(), 'purpose', 'not-applicable', 'system', 'System excluded from this review');
  assert(R.questions(systemNA, 'n:queue').every(q => q.notApplicable));
  assert.equal(R.pending(systemNA).length, 0, 'N/A propagates through system and local prerequisites');
  assert.deepEqual(M.importModel(M.parse(JSON.stringify(queueNA))).review, queueNA.review);
  const added = R.command(model, { type: 'add-node', id: crypto.randomUUID(), name: 'Isolated process', kind: 'Process' });
  assert.deepEqual(added.review.answers, model.review.answers, 'Disconnected process must not stale unrelated answers');
  const connected = R.command(model, { type: 'add-flow', id: crypto.randomUUID(), from: 'worker', to: 'table', label: 'Additional projection' });
  assert(!R.answer(connected, 'system', 'actors').needsReview);
  assert(R.answer(connected, 'n:worker', 'access').needsReview);
  assert(!R.answer(connected, 'e:demo-0', 'identity').needsReview);
  const privilege = R.questions(connected, 'n:worker').find(q => q.id === 'privilege');
  assert(!privilege.blocked && privilege.prerequisiteNeedsReview);
  assert(R.pending(connected).some(q => q.target === 'n:worker' && q.id === 'access'));
  const actor = R.command(model, { type: 'add-node', id: crypto.randomUUID(), name: 'New external actor', kind: 'External actor' });
  assert(R.answer(actor, 'system', 'actors').needsReview);
  assert(!R.questions(actor, 'n:table').find(q => q.id === 'access').blocked);
  const changed = cmd(model, 'tenants', 'single');
  assert(!R.questions(changed).some(q => q.id === 'isolation'));
  assert(R.answer(changed, 'e:demo-0', 'identity').needsReview);
  assert(!R.answer(changed, 'system', 'purpose').needsReview);
  assert(R.pending(changed).some(q => q.id === 'data'));
  const dependency = structuredClone(model); dependency.edges[0].kind = 'dependency';
  assert.deepEqual(R.questions(dependency, 'e:demo-0'), []);
  const n = { id: 't', title: 'Replay', target: 'n:worker', category: 'Tampering', status: 'mitigated', mitigation: 'Idempotency', note: 'Plan', severity: 'medium', needsReview: false };
  assert.throws(() => R.finding({ ...model, threats: [n] }, 't'), /owner and validation evidence/);
  const finding = R.finding({ ...model, threats: [{ ...n, owner: 'Reviewer', evidence: 'run-1/report.md' }] }, 't');
  assert.equal(finding.threats[0].verification, 'recorded');
  const v1 = structuredClone(model); v1.version = 1; delete v1.review; v1.documentType = 'review'; v1.threats = [n];
  const migrated = M.validate(v1);
  assert(migrated.review.legacy);
  assert.equal(migrated.threats[0].verification, 'pending');
  assert.throws(() => M.validate({ ...model, review: { ...model.review, catalogVersion: 99 } }), /catalog/);
  const fresh = structuredClone(model); fresh.documentType = 'snapshot'; fresh.scope.capturedAt = 'new'; fresh.review = R.fresh(); fresh.threats = [];
  const refreshed = M.merge(model, fresh);
  assert(refreshed.review.answers.every(a => a.needsReview));
  assert.equal(refreshed.review.revision, model.review.revision + 1);
  const proposed = structuredClone(model); proposed.nodes.push({ id: 'bank', name: 'Bank', type: 'External actor', status: 'PROPOSED', zone: '', x: 1, y: 1 });
  assert(M.merge(proposed, fresh).nodes.some(n => n.id === 'bank'));
});
